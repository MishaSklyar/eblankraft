typedef struct {
    uint32_t color;
    float x, y, z;
} ColorVertex2D;

void font_init(void) {
    // No special setup needed for bitmap font
}

void font_draw_char(int x, int y, char c, uint32_t color, int scale) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t* glyph = font_8x8[c - 32];
    
    // Count active pixel blocks to batch draw
    ColorVertex2D verts[128]; // max 64 pixels * 2 verts for GU_SPRITES
    int vert_count = 0;

    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                float px = x + col * scale;
                float py = y + row * scale;
                
                verts[vert_count].color = color;
                verts[vert_count].x = px;
                verts[vert_count].y = py;
                verts[vert_count].z = 0.0f;
                vert_count++;

                verts[vert_count].color = color;
                verts[vert_count].x = px + scale;
                verts[vert_count].y = py + scale;
                verts[vert_count].z = 0.0f;
                vert_count++;
            }
        }
    }

    if (vert_count > 0) {
        ColorVertex2D* v = (ColorVertex2D*)sceGuGetMemory(vert_count * sizeof(ColorVertex2D));
        if (!v) return;
        memcpy(v, verts, vert_count * sizeof(ColorVertex2D));

        sceGuDisable(GU_TEXTURE_2D);
        sceGuDrawArray(GU_SPRITES, GU_COLOR_8888 | GU_VERTEX_32BITF | GU_TRANSFORM_2D, vert_count, NULL, v);
        sceGuEnable(GU_TEXTURE_2D);
    }
}

void font_draw_text(int x, int y, const char* str, uint32_t color, int scale) {
    if (!str) return;
    int cur_x = x;
    int cur_y = y;
    
    while (*str) {
        char c = *str;
        if (c == '\n') {
            cur_y += 9 * scale;
            cur_x = x;
        } else {
            font_draw_char(cur_x, cur_y, c, color, scale);
            cur_x += 8 * scale;
        }
        str++;
    }
}

void font_draw_text_shadow(int x, int y, const char* str, uint32_t color, int scale) {
    uint32_t shadow_col = RGBA(20, 20, 20, (color >> 24) & 0xFF);
    font_draw_text(x + scale, y + scale, str, shadow_col, scale);
    font_draw_text(x, y, str, color, scale);
}

int font_get_text_width(const char* str, int scale) {
    if (!str) return 0;
    return strlen(str) * 8 * scale;
}
