// Rebuilds js/three.min.js from the `three` npm package.
//   npm install && node tools/build_three.mjs
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
const { version } = JSON.parse(readFileSync(new URL('../node_modules/three/package.json', import.meta.url)));
await build({
    entryPoints: [new URL('./three_entry.mjs', import.meta.url).pathname],
    outfile: new URL('../js/three.min.js', import.meta.url).pathname,
    bundle: true, minify: true, format: 'iife', target: 'es2020',
    legalComments: 'none',
    logOverride: { 'commonjs-variable-in-esm': 'silent' },   // intentional UMD-style export, see three_entry.mjs
    banner: { js: `/* three.js ${version} (MIT, Three.js Authors) + GLTFLoader. Generated by tools/build_three.mjs - do not edit. */` },
});
console.log('built js/three.min.js from three', version);
