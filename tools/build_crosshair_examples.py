#!/usr/bin/env python3
"""Builds js/crosshair_examples.js from crosshairs/examples/*.lua.

The .lua files are the source of truth. After editing or adding one, run:

    python3 tools/build_crosshair_examples.py

Use --check to fail when the generated file is out of date (the test suite does this too).
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'crosshairs' / 'examples'
OUT = ROOT / 'js' / 'crosshair_examples.js'


def build():
    items = []
    for path in sorted(SRC.glob('*.lua')):
        text = path.read_text(encoding='utf-8')
        name = re.search(r'^--\s*@name\s+(.+)$', text, re.M)
        author = re.search(r'^--\s*@author\s+(.+)$', text, re.M)
        if not name:
            sys.exit(f'{path.name}: missing a "-- @name" line in its header')
        items.append({
            'id': path.stem,
            'name': name.group(1).strip(),
            'author': author.group(1).strip() if author else '',
            'src': text,
        })
    header = '// Generated by tools/build_crosshair_examples.py from crosshairs/examples/*.lua. Do not edit by hand.\n'
    return header + 'window.CROSSHAIR_EXAMPLES = ' + json.dumps(items, ensure_ascii=False, indent=1) + ';\n', len(items)


if __name__ == '__main__':
    text, count = build()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            sys.exit('js/crosshair_examples.js is out of date: run python3 tools/build_crosshair_examples.py')
        print(f'ok: {count} examples are up to date')
    else:
        OUT.write_text(text, encoding='utf-8')
        print(f'wrote {OUT.relative_to(ROOT)} ({count} examples)')
